"""Generate source-derived wiki reference data and check maintained documentation."""

import argparse
import json
import re
import sys
from pathlib import Path, PurePath
from urllib.parse import quote, unquote, urlsplit


ROOT = Path(__file__).resolve().parents[1]
REFERENCE = Path("docs") / "wiki" / "developers" / "Reference.md"
JAVA_ROOT = Path("src") / "main" / "java" / "com" / "ordana" / "immersive_weathering"
CONFIG_TOKEN = re.compile(
    r' builder\.push\("(?P<push>[^"]+)"\)'
    r"|(?P<pop>builder\.pop\(\))"
    r'|(?P<field>[A-Z][A-Z0-9_]*)\s*=\s*builder'
    r'(?:\.comment\(.*?\))?\s*\.define\("(?P<key>[^"]+)",\s*(?P<args>.*?)\);',
    re.DOTALL | re.VERBOSE,
)


def properties(text: str) -> dict[str, str]:
    result = {}
    for line in text.splitlines():
        line = line.strip()
        if line and not line.startswith(("#", "!")) and "=" in line:
            key, value = line.split("=", 1)
            result[key.strip()] = value.strip()
    return result


def config_rows(source: str) -> list[tuple[str, str, str]]:
    source = re.sub(r"/\*.*?\*/|//[^\n]*", "", source, flags=re.DOTALL)
    sections = []
    rows = []
    fields = set()
    for match in CONFIG_TOKEN.finditer(source):
        if match["push"] is not None:
            sections.append(match["push"])
        elif match["pop"] is not None:
            if not sections:
                raise ValueError("Config section pop without matching push")
            sections.pop()
        else:
            key = ".".join([*sections, match["key"]])
            rows.append((key, re.sub(r"\s+", " ", match["args"]).strip(), match["field"]))
            fields.add(match["field"])
    declared = set(re.findall(
        r"^\s*public static (?:final )?Supplier<.+>\s+([A-Z][A-Z0-9_]*);",
        source, re.MULTILINE,
    ))
    if fields != declared:
        raise ValueError(
            f"Config definitions need parser review: missing={sorted(declared - fields)}, "
            f"unexpected={sorted(fields - declared)}"
        )
    if sections:
        raise ValueError(f"Unclosed config sections: {sections}")
    return rows


def source_link(root: Path, path: Path, label: str | None = None) -> str:
    relative = path.relative_to(root).as_posix()
    return f"[{label or relative}](../../../{relative})"


def table_cell(value: str) -> str:
    return value.replace("|", r"\|").replace("\n", " ")


def path_sort_key(path: PurePath) -> str:
    return path.as_posix()


def moonlight_coordinates(source: str) -> list[str]:
    return re.findall(r'"([^"\n]*:(?:selene|moonlight)[^"\n]*)"', source)


def generate(root: Path) -> str:
    props = properties((root / "gradle.properties").read_text(encoding="utf-8"))
    manifest_path = root / "src" / "main" / "resources" / "fabric.mod.json"
    manifest_text = manifest_path.read_text(encoding="utf-8")
    for token, key in (
        ("${version}", "mod_version"),
        ("${fabric_loader_version}", "fabric_loader_version"),
        ("${moonlight_min_version}", "moonlight_min_version"),
    ):
        manifest_text = manifest_text.replace(token, props[key])
    manifest = json.loads(manifest_text)
    lines = [
        "# Generated source reference", "",
        "[Wiki home](../README.md) | [Players](../players/README.md) | [Developers](README.md)", "",
        "<!-- Generated by tools/wiki.py. Do not edit by hand. -->",
        "Regenerate with `python tools\\wiki.py --write` from the repository root.",
        "This records declarations, not resolved dependencies or verified gameplay.",
        "The build is a single root Fabric Loom project for Minecraft 1.20.1.", "",
        "## Build declarations", "",
        "| Property | Value |", "| --- | --- |",
    ]
    for key, value in sorted(props.items()):
        lines.append(f"| `{key}` | `{table_cell(value)}` |")
    settings = (root / "settings.gradle").read_text(encoding="utf-8")
    if re.search(r"\binclude\s*\(", settings):
        raise ValueError("Expected a single root project without included modules")
    lines.extend(["", "Build project: root only (no subprojects).", "",
                  "### Moonlight build coordinates", "",
                  "| Build file | Declaration |", "| --- | --- |"])
    build = root / "build.gradle"
    for coordinate in moonlight_coordinates(build.read_text(encoding="utf-8")):
        lines.append(f"| {source_link(root, build)} | `{table_cell(coordinate)}` |")
    lines.extend(["", "## Fabric metadata", "",
                  f"Source: {source_link(root, manifest_path)}", "",
                  f"License declaration: `{manifest['license']}`", "",
                  "### Runtime dependencies", "",
                  "| Mod ID | Requirement |", "| --- | --- |"])
    for mod, requirement in sorted(manifest["depends"].items()):
        lines.append(f"| `{mod}` | `{requirement}` |")
    lines.extend(["", "### Entrypoints", "",
                  "| Type | Registered classes |", "| --- | --- |"])
    for kind, entries in sorted(manifest["entrypoints"].items()):
        lines.append(f"| `{kind}` | {', '.join(f'`{e}`' for e in entries) or '(none)'} |")
    lines.extend(["", "### Registered mixins", ""])
    for entry in manifest["mixins"]:
        name = entry if isinstance(entry, str) else entry["config"]
        path = root / "src" / "main" / "resources" / name
        if not path.is_file():
            raise ValueError(f"Mixin manifest not found: {name}")
        config = json.loads(path.read_text(encoding="utf-8"))
        lines.extend([f"#### {name}", "", f"Source: {source_link(root, path)}", "",
                      "| Side | Mixin class |", "| --- | --- |"])
        for side in ("mixins", "client", "server"):
            for mixin in config.get(side, []):
                lines.append(f"| `{side}` | `{config['package']}.{mixin}` |")
        lines.append("")
    lines.extend(["", "## Configuration definitions", "",
                  "The argument column preserves Java expressions: default first, then any bounds.",
                  "Keys are grouped by the source's section stack; a definition is not proof every",
                  "consumer honors it. Configuration suppliers not recognized by the parser fail the check.", ""])
    for name in ("CommonConfigs", "ClientConfigs"):
        path = root / JAVA_ROOT / "configs" / f"{name}.java"
        rows = config_rows(path.read_text(encoding="utf-8"))
        lines.extend([f"### {name}", "", f"Source: {source_link(root, path)}", "",
                      "| Key | Default and optional bounds | Source field |", "| --- | --- | --- |"])
        for key, arguments, field in rows:
            lines.append(f"| `{key}` | `{table_cell(arguments)}` | `{field}` |")
        lines.append("")
    lines.extend(["", "## Moonlight import inventory", "",
                  "Root Java sources only. Imports indicate coupling, not measured runtime cost.",
                  "Annotations, utility APIs, and functional dependencies are all included.", "",
                  "| Source file | Imported API symbols |", "| --- | --- |"])
    base = root / "src" / "main" / "java"
    for path in sorted(base.rglob("*.java"), key=path_sort_key):
        imports = re.findall(r"^import (?:static )?(net\.mehvahdjukaar\.moonlight\.[^;]+);",
                             path.read_text(encoding="utf-8"), re.MULTILINE)
        if imports:
            symbols = ", ".join(f"`{symbol.removeprefix('net.mehvahdjukaar.moonlight.')}`"
                                for symbol in sorted(set(imports)))
            lines.append(f"| {source_link(root, path)} | {symbols} |")
    tick_path = root / JAVA_ROOT / "data" / "block_growths" / "TickSource.java"
    tick_names = re.findall(r'^\s*[A-Z_]+\("([^"]+)"\)', tick_path.read_text(encoding="utf-8"), re.MULTILINE)
    if not tick_names:
        raise ValueError("No tick sources found; review TickSource parsing")
    lines.extend(["", "## Data inventory", "",
                  "Growth tick sources: " + ", ".join(f"`{name}`" for name in tick_names) + ".", ""])
    data_root = root / "src" / "main" / "resources" / "data"
    for directory in ("block_growths", "fluid_generators"):
        lines.extend([f"### {directory}", "", "| Resource ID | Definition |", "| --- | --- |"])
        for namespace in sorted(data_root.iterdir(), key=path_sort_key):
            for path in sorted((namespace / directory).rglob("*.json"), key=path_sort_key):
                resource = path.relative_to(namespace / directory).with_suffix("").as_posix()
                lines.append(f"| `{namespace.name}:{resource}` | {source_link(root, path)} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def markdown_targets(text: str) -> list[str]:
    text = re.sub(r"(?ms)^ *(`{3,}|~{3,})[^\n]*\n.*?^ *\1[ \t]*$", "", text)
    text = re.sub(r"`[^`\n]+`", "", text)
    return re.findall(r"\[[^\]]*\]\(([^)\s]+)\)", text)


def link_errors(root: Path, path: Path) -> list[str]:
    errors = []
    for target in markdown_targets(path.read_text(encoding="utf-8")):
        parsed = urlsplit(target)
        if parsed.scheme in ("https", "http", "mailto"):
            continue
        if parsed.scheme or parsed.netloc:
            errors.append(f"{path.relative_to(root)}: unsupported link {target}")
            continue
        if not parsed.path:
            continue
        destination = (path.parent / unquote(parsed.path)).resolve()
        if not destination.is_relative_to(root.resolve()) or not destination.exists():
            errors.append(f"{path.relative_to(root)}: missing repository destination {target}")
    return errors


def check(root: Path, expected: str) -> list[str]:
    errors = []
    reference = root / REFERENCE
    if not reference.is_file() or reference.read_text(encoding="utf-8") != expected:
        errors.append("Generated reference is stale or missing; run python tools\\wiki.py --write")
    wiki = root / "docs" / "wiki"
    pages = sorted(wiki.rglob("*.md"), key=path_sort_key)
    documents = [root / name for name in ("README.md", "CONTRIBUTING.md", "AGENTS.md")]
    documents.append(root / ".github" / "pull_request_template.md")
    for path in [*documents, *pages]:
        errors.extend(link_errors(root, path))
    hubs = [wiki / "README.md", wiki / "players" / "README.md", wiki / "developers" / "README.md"]
    for page in pages:
        resolved = {
            (page.parent / unquote(urlsplit(target).path)).resolve()
            for target in markdown_targets(page.read_text(encoding="utf-8"))
            if not urlsplit(target).scheme and urlsplit(target).path
        }
        for hub in hubs:
            if page != hub and hub.resolve() not in resolved:
                errors.append(f"{page.relative_to(root)}: missing navigation to {hub.relative_to(root)}")
    return errors


def wiki_slug(relative: Path) -> str:
    if relative == Path("README.md"):
        return "Home"
    audience = relative.parts[0].capitalize()
    if relative.name == "README.md":
        return audience
    return f"{audience}-{relative.stem}"


def wiki_content(root: Path, page: Path, repo_url: str, ref: str) -> str:
    wiki_root = root / "docs" / "wiki"
    text = page.read_text(encoding="utf-8")

    def replace_link(match: re.Match) -> str:
        if match["inline"] is not None:
            return match[0]
        target = match["target"]
        parsed = urlsplit(target)
        if parsed.scheme or parsed.netloc or not parsed.path:
            return match[0]
        destination = (page.parent / unquote(parsed.path)).resolve()
        if destination.is_relative_to(wiki_root.resolve()) and destination.suffix == ".md":
            slug = wiki_slug(destination.relative_to(wiki_root.resolve()))
            url = f"{repo_url}/wiki/{quote(slug)}"
        else:
            kind = "tree" if destination.is_dir() else "blob"
            relative = destination.relative_to(root.resolve()).as_posix()
            url = f"{repo_url}/{kind}/{quote(ref, safe='')}/{quote(relative)}"
        if parsed.fragment:
            url += "#" + parsed.fragment
        return f"{match['label']}({url})"

    # Keep examples intact; only translate links in prose, not fenced/inline code.
    pieces = re.split(r"(?ms)(^ *(`{3,}|~{3,})[^\n]*\n.*?^ *\2[ \t]*$)", text)
    rendered = []
    for index in range(0, len(pieces), 3):
        rendered.append(re.sub(
            r"(?P<inline>`+)[^\n]*?(?P=inline)|"
            r"(?P<label>\[[^\]]*\])\((?P<target>[^)\s]+)\)",
            replace_link, pieces[index],
        ))
        if index + 1 < len(pieces):
            rendered.append(pieces[index + 1])
    return "".join(rendered)


def export_wiki(root: Path, output: Path, repo_url: str, ref: str) -> None:
    root = root.resolve()
    parsed = urlsplit(repo_url)
    if parsed.scheme != "https" or not parsed.netloc or parsed.username or parsed.password:
        raise ValueError("Repository URL must be HTTPS without credentials")
    repo_url = repo_url.rstrip("/")
    output = output.resolve()
    if output.is_relative_to((root / "docs" / "wiki").resolve()):
        raise ValueError("Export destination must not overwrite the source wiki")
    output.mkdir(parents=True, exist_ok=True)
    wiki_root = root / "docs" / "wiki"
    pages = sorted(wiki_root.rglob("*.md"), key=path_sort_key)
    exported = {}
    for page in pages:
        slug = wiki_slug(page.relative_to(wiki_root))
        filename = slug + ".md"
        if filename in exported:
            raise ValueError(f"Duplicate wiki page slug: {slug}")
        exported[filename] = wiki_content(root, page, repo_url, ref)
    sidebar = [f"[Home]({repo_url}/wiki/Home)", ""]
    for audience in ("players", "developers"):
        title = audience.capitalize()
        sidebar.extend([f"## [{title}]({repo_url}/wiki/{title})", ""])
        # Match each audience hub's reading order; keep new unlisted pages visible.
        hub = wiki_root / audience / "README.md"
        ordered = []
        for target in markdown_targets(hub.read_text(encoding="utf-8")):
            parsed = urlsplit(target)
            if parsed.scheme or parsed.netloc or not parsed.path:
                continue
            page = (hub.parent / unquote(parsed.path)).resolve()
            if page.parent == hub.parent.resolve() and page.suffix == ".md" and page.name != "README.md":
                if page not in ordered and page in pages:
                    ordered.append(page)
        ordered.extend(page for page in pages
                       if page.parent.name == audience and page.name != "README.md" and page not in ordered)
        for page in ordered:
            slug = wiki_slug(page.relative_to(wiki_root))
            label = page.read_text(encoding="utf-8").splitlines()[0].removeprefix("# ")
            sidebar.append(f"- [{label}]({repo_url}/wiki/{quote(slug)})")
        sidebar.append("")
    exported["_Sidebar.md"] = "\n".join(sidebar).rstrip() + "\n"
    if "Developers-Feature-testing.md" in exported and "Developers-Test-results.md" in exported:
        # Published releases link to this old slug; retain a landing page outside the sidebar.
        exported["Players-Feature-testing.md"] = (
            "# Testing has moved\n\n"
            f"[Home]({repo_url}/wiki/Home) | [Players]({repo_url}/wiki/Players) | "
            f"[Developers]({repo_url}/wiki/Developers)\n\n"
            f"Use the [in-game test sheet]({repo_url}/wiki/Developers-Feature-testing) "
            "for reusable feature replication instructions.\n\n"
            f"Use [test results]({repo_url}/wiki/Developers-Test-results) "
            "for dated outcomes, tested versions and coverage limits.\n"
        )
    exported["_Footer.md"] = (
        f"[Players]({repo_url}/wiki/Players) | [Developers]({repo_url}/wiki/Developers)\n\n"
        f"Published from [repository documentation]({repo_url}/tree/{quote(ref, safe='')}/docs/wiki) "
        f"at `{ref}`. Edit the repository copy and republish; Wiki edits are not synchronized back.\n"
    )
    tracking = output / ".wiki-published-pages.json"
    previous = json.loads(tracking.read_text(encoding="utf-8")) if tracking.is_file() else []
    if not isinstance(previous, list) or any(
        not isinstance(name, str) or not re.fullmatch(r"[A-Za-z0-9_-]+\.md", name)
        for name in previous
    ):
        raise ValueError("Invalid previously published page inventory")
    for name, content in exported.items():
        (output / name).write_text(content, encoding="utf-8", newline="\n")
    for name in set(previous) - exported.keys():
        obsolete = output / name
        if obsolete.is_file():
            obsolete.unlink()
    tracking.write_text(json.dumps(sorted(exported), indent=2) + "\n", encoding="utf-8", newline="\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument("--write", action="store_true", help="Regenerate the source-derived reference")
    modes.add_argument("--check", action="store_true", help="Check freshness, destinations, and navigation")
    modes.add_argument("--export", type=Path, metavar="WIKI_CHECKOUT", help="Export pages to a GitHub Wiki checkout")
    parser.add_argument("--repo-url", help="HTTPS repository URL for exported page/source links")
    parser.add_argument("--ref", help="Published repository commit or ref matching this documentation")
    args = parser.parse_args()
    expected = generate(ROOT)
    if args.write:
        (ROOT / REFERENCE).write_text(expected, encoding="utf-8", newline="\n")
        print(f"Generated {REFERENCE}")
        return 0
    errors = check(ROOT, expected)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    if args.export is not None:
        if not args.repo_url or not args.ref:
            parser.error("--export requires --repo-url and --ref")
        export_wiki(ROOT, args.export, args.repo_url, args.ref)
        print(f"Exported Wiki pages to {args.export}")
        return 0
    print("Wiki reference, local destinations, and player/developer navigation are current.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
